-- The admin audit log: who changed what, and when.
--
-- Apply AFTER every earlier migration (it redefines admin functions from
-- 20261001000003, 20261002000002, 20261002000004, 20261002000005,
-- 20261003000001, 20261003000002 and 20261013000002). ONE transaction.
--
-- ONE ROW PER ADMIN ACTION, written INSIDE the action's own function, so a row
-- exists if and only if the action happened: a refused or rolled-back action
-- leaves nothing. The functions below are copied VERBATIM from the migration
-- that last defined them, with only the `perform public.admin_audit(...)` call
-- added (generated by script, each insertion at an exact anchor). No grants
-- change: `create or replace` keeps them.
--
-- NAMES ARE COPIED, not joined. The admin's name and the student's name are
-- stored on the row, so "deleted the account of Sok" still reads after Sok's
-- account is gone, and actor_id is set null if the admin's own account goes.
--
-- Not logged, deliberately: draft SAVES (frequent, never seen by students; the
-- draft keeps updated_by), and students' own actions such as Delete my account.
--
-- Read through admin_audit_log() only. Every admin sees the log EXCEPT role
-- changes (make or remove an admin), which only the owner sees.

begin;

create table if not exists public.audit_log (
  id           bigint generated always as identity primary key,
  at           timestamptz not null default now(),
  actor_id     uuid references auth.users (id) on delete set null,
  actor_name   text,
  action       text not null check (action in (
    'role_grant', 'role_revoke',
    'student_delete',
    'kruai_limits', 'kruai_pause', 'kruai_resume',
    'announcement_publish', 'announcement_end',
    'photo_kept', 'photo_deleted',
    'mistake_fixed', 'mistake_not_mistake',
    'error_fixed',
    'content_publish', 'content_unpublish', 'content_restore',
    'content_discard', 'content_import'
  )),
  target_kind  text,
  target_id    text,
  target_label text,
  details      jsonb not null default '{}'::jsonb
);

create index if not exists audit_log_at_idx on public.audit_log (id desc);

alter table public.audit_log enable row level security;
-- No policies: written by admin_audit(), read by admin_audit_log().

-- The writer. Called only from the security definer admin functions below.
create or replace function public.admin_audit(
  p_action       text,
  p_target_kind  text,
  p_target_id    text,
  p_target_label text,
  p_details      jsonb
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.audit_log (actor_id, actor_name, action, target_kind, target_id, target_label, details)
  values (
    auth.uid(),
    (select p.display_name from public.profiles p where p.id = auth.uid()),
    p_action,
    p_target_kind,
    left(p_target_id, 300),
    left(p_target_label, 300),
    coalesce(p_details, '{}'::jsonb)
  );
end;
$$;

revoke all on function public.admin_audit(text, text, text, text, jsonb) from public, anon, authenticated;

-- The reader: newest first, at most p_limit rows (1..200) older than p_before.
create or replace function public.admin_audit_log(
  p_before bigint default null,
  p_limit  integer default 100
)
returns table (
  id           bigint,
  at           timestamptz,
  actor_id     uuid,
  actor_name   text,
  action       text,
  target_kind  text,
  target_id    text,
  target_label text,
  details      jsonb
)
language plpgsql
security definer
set search_path = ''
as $$
declare
  is_owner boolean := public.has_role('owner');
begin
  if not public.is_app_admin() then
    raise exception 'admin_audit_log: not an admin' using errcode = '42501';
  end if;

  return query
  select l.id, l.at, l.actor_id, l.actor_name, l.action,
         l.target_kind, l.target_id, l.target_label, l.details
  from public.audit_log l
  where (p_before is null or l.id < p_before)
    and (is_owner or l.action not in ('role_grant', 'role_revoke'))
  order by l.id desc
  limit greatest(1, least(coalesce(p_limit, 100), 200));
end;
$$;

revoke all on function public.admin_audit_log(bigint, integer) from public, anon;
grant execute on function public.admin_audit_log(bigint, integer) to authenticated;

